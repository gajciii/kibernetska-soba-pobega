async function expireNewGameCooldown(page: Page) {
  const databaseUrl = process.env.TEST_DATABASE_URL || 'postgres://operacija404@127.0.0.1:55432/operacija404_test';
  if (new URL(databaseUrl).pathname !== '/operacija404_test') throw new Error('Premik omejitve je dovoljen samo v bazi operacija404_test.');
  const bootstrap = await (await page.request.get('/api/session')).json();
  const pool = new pg.Pool({ connectionString: databaseUrl, connectionTimeoutMillis: 5000, max: 1 });
  try {
    // Premaknemo le čas lastne testne seje; browser clock ne vpliva na strežnik.
    const changed = await pool.query("UPDATE game_sessions SET next_start_at=now()-interval '1 second' WHERE csrf=$1 AND progress IS NULL", [bootstrap.csrfToken]);
    expect(changed.rowCount).toBe(1);
  } finally { await pool.end(); }
}

async function checkLayout(page: Page) {
  const width = await page.evaluate(() => ({ content: document.documentElement.scrollWidth, window: window.innerWidth }));
  expect(width.content).toBeLessThanOrEqual(width.window + 1);
}
async function expectFirstStage(page: Page) {
  await expect(page.getByTestId('dark-entry')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Odpri prvo sled', exact: true })).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Razbij skrivno sporočilo', exact: true })).toBeVisible();
}
async function begin(page: Page, name = 'Preizkusna skupina') {
  const field = page.getByLabel('Ime skupine', { exact: true });
  if (!(await field.inputValue()).trim()) await field.fill(name);
  await page.getByRole('button', { name: 'Začni preiskavo', exact: true }).click();
}
async function submit(page: Page, answer?: string, label = 'Odgovor') {
  if (answer) await page.getByLabel(label, { exact: true }).fill(answer);
  await page.getByRole('button', { name: 'Preveri odgovor', exact: true }).click();
  await expect(page.locator('main[aria-busy]')).toHaveAttribute('aria-busy', 'false');
}
async function next(page: Page) {
  const before = await page.locator('.stage-breadcrumb').textContent();
  await page.getByRole('button', { name: 'Nadaljuj', exact: true }).click();
  await expect(page.locator('.stage-breadcrumb')).not.toHaveText(before!);
  await expect(page.locator('main[aria-busy]')).toHaveAttribute('aria-busy', 'false');
  await expect(page.getByTestId('dark-entry')).toHaveCount(0);
  await checkLayout(page);
  await expect(page.locator('.stage-intro')).toBeVisible();
  const story = await page.locator('.stage-intro').boundingBox();
  const workbench = await page.locator('.desktop-window').boundingBox();
  expect(story!.y + story!.height).toBeLessThanOrEqual(workbench!.y);
}

